def compute_fingerprint(data: dict[str, Any]) -> str:
    """Compute a SHA-256 fingerprint for deduplication.

    Non-metadata fields are serialized deterministically and hashed.
    """
    sanitized = {k: v for k, v in data.items() if k not in ("fingerprint", "ingestion_time")}
    canonical = json.dumps(sanitized, sort_keys=True, default=str)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def to_payload(record: EEGChunkEvent | EHREvent | FeatureEvent | AlertEvent | DLQRecord) -> dict[str, Any]:
    """Convert any event record to a plain dictionary."""
    return asdict(record)


def to_json(record: EEGChunkEvent | EHREvent | FeatureEvent | AlertEvent | DLQRecord) -> str:
    """Serialize an event record to a JSON string."""
    return json.dumps(asdict(record), default=str)


def validate_required_fields(payload: dict[str, Any], required_fields: set[str]) -> list[str]:
    """Return a sorted list of field names that are missing or empty."""
    return [field for field in sorted(required_fields) if payload.get(field) in (None, "")]


