@dataclass(slots=True)
class EEGChunkEvent:
    """A single windowed chunk of multi-channel EEG data."""

    patient_id: str
    session_id: str
    event_time: str
    site_id: str
    channel_count: int
    sampling_rate_hz: float
    window_seconds: float
    source_uri: str
    fingerprint: str = ""

    def __post_init__(self) -> None:
        if not self.fingerprint:
            self.fingerprint = compute_fingerprint(self.to_dict())

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> EEGChunkEvent:
        return cls(
            patient_id=data["patient_id"],
            session_id=data["session_id"],
            event_time=data["event_time"],
            site_id=data["site_id"],
            channel_count=int(data["channel_count"]),
            sampling_rate_hz=float(data["sampling_rate_hz"]),
            window_seconds=float(data["window_seconds"]),
            source_uri=data.get("source_uri", ""),
            fingerprint=data.get("fingerprint", ""),
        )


