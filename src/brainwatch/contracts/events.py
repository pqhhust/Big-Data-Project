@dataclass(slots=True)
class AlertEvent:
    """An anomaly alert generated by the serving layer."""

    patient_id: str
    session_id: str
    alert_time: str
    severity: str
    anomaly_score: float
    explanation: str
    alert_id: str = ""

    def __post_init__(self) -> None:
        if not self.alert_id:
            self.alert_id = compute_fingerprint(
                {"patient_id": self.patient_id, "alert_time": self.alert_time, "severity": self.severity}
            )[:16]

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> AlertEvent:
        return cls(
            patient_id=data["patient_id"],
            session_id=data["session_id"],
            alert_time=data["alert_time"],
            severity=data["severity"],
            anomaly_score=float(data["anomaly_score"]),
            explanation=data.get("explanation", ""),
            alert_id=data.get("alert_id", ""),
        )


@dataclass(slots=True)
class DLQRecord:
    """A dead-letter queue record capturing a failed event."""

    original_topic: str
    original_payload: dict[str, Any]
    error_reason: str
    error_timestamp: str = ""
    retry_count: int = 0
    fingerprint: str = ""

    def __post_init__(self) -> None:
        if not self.error_timestamp:
            self.error_timestamp = datetime.now(timezone.utc).isoformat()
        if not self.fingerprint:
            self.fingerprint = compute_fingerprint(self.original_payload)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> DLQRecord:
        return cls(
            original_topic=data["original_topic"],
            original_payload=data["original_payload"],
            error_reason=data["error_reason"],
            error_timestamp=data.get("error_timestamp", ""),
            retry_count=int(data.get("retry_count", 0)),
            fingerprint=data.get("fingerprint", ""),
        )


@dataclass(slots=True)
class BronzeEEGRecord:
    """A bronze-layer EEG record with ingestion metadata."""

    patient_id: str
    session_id: str
    event_time: str
    site_id: str
    channel_count: int
    sampling_rate_hz: float
    window_seconds: float
    source_uri: str
